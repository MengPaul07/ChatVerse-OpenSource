export default function LegalPage() {
  const { pathname } = useLocation();
  const siteMode = useSiteMode();
  const isPrivacy = pathname === "/privacy";
  const isShowcase = siteMode === "showcase";
  const title = isPrivacy ? "隐私政策" : "用户协议";
  const Icon = isPrivacy ? ShieldCheck : FileText;
  const sections = isShowcase
    ? isPrivacy ? SHOWCASE_PRIVACY : SHOWCASE_TERMS
    : isPrivacy ? FULL_PRIVACY : FULL_TERMS;

  return (
    <div className="workspace-page legal-page page-enter">
      <header className="page-header legal-page-header">
        <div>
          <Link className="legal-back-link" to={isShowcase ? "/showcase" : "/"}>
            <ArrowLeft size={15} />{isShowcase ? "返回编排展示" : "返回首页"}
          </Link>
          <p className="eyebrow">ChatVerse · {isShowcase ? "公开展示说明" : "服务规则"}</p>
          <h1>{title}</h1>
          <p>{isShowcase ? "适用于当前智能体编排公开展示页面。" : "请了解 ChatVerse 如何处理本地作品、模型连接与智能体运行数据。"}</p>
        </div>
      </header>

      <section className={`legal-document${isShowcase ? " is-compact" : ""}`}>
        <div className="legal-document-heading">
          <span><Icon size={18} /></span>
          <div><h2>{title}</h2><small>最后更新：2026 年 8 月 8 日</small></div>
        </div>
        {!isShowcase && (
          <p className="legal-document-notice">重要提示：模型服务由您自行选择并提供 API Key。请特别阅读第三方模型、用户内容、生成结果与本地数据备份相关条款。</p>
        )}
        {sections.map((section) => (
          <section className="legal-section" key={section.title}>
            <h3>{section.title}</h3>
            {section.paragraphs?.map((paragraph) => <p key={paragraph}>{paragraph}</p>)}
            {section.items && <ul>{section.items.map((item) => <li key={item}>{item}</li>)}</ul>}
          </section>
        ))}
      </section>
    </div>
  );
}
